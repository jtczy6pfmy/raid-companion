import assert from 'node:assert/strict';
import {parseCSV,guessMapping,validateRoster,MAX_BYTES} from './roster-import.mjs';
let count=0;const test=(name,fn)=>{fn();count++;console.log('PASS '+name);};
test('BOM and CRLF',()=>assert.equal(validateRoster(parseCSV('\uFEFFName,Level,Rank\r\nKael,60,6\r\n'),{name:0,level:1,rank:2})[0].level,60));
test('semicolon',()=>assert.equal(parseCSV('Name;Level\nKael;60').headers.length,2));
test('quoted delimiter, newline and escaped quote',()=>assert.equal(parseCSV('Name,Level\n"Cat, ""A""\nB",50').rows[0][0],'Cat, "A"\nB'));
test('aliases',()=>assert.equal(guessMapping(['Champion Name','Lvl']).name,0));
test('bad quote',()=>assert.throws(()=>parseCSV('Name\n"Kael')));
test('text after quote',()=>assert.throws(()=>parseCSV('Name\n"Kael"x')));
test('duplicate headers',()=>assert.throws(()=>parseCSV('Name,name\nA,B')));
test('wrong width',()=>assert.throws(()=>parseCSV('Name,Level\nA')));
test('invalid numbers',()=>assert.throws(()=>validateRoster(parseCSV('Name,Level\nA,61'),{name:0,level:1})));
test('empty name',()=>assert.throws(()=>validateRoster(parseCSV('Name,Level\n,50'),{name:0,level:1})));
test('duplicate ID',()=>assert.throws(()=>validateRoster(parseCSV('Name,ID\nA,1\nB,1'),{name:0,id:1})));
test('duplicate names retained',()=>assert.equal(validateRoster(parseCSV('Name\nKael\nKael'),{name:0}).length,2));
test('mapping required',()=>assert.throws(()=>validateRoster(parseCSV('Name\nA'),{name:-1})));
test('reused mapping',()=>assert.throws(()=>validateRoster(parseCSV('Name\nA'),{name:0,id:0})));
test('formula retained as inert text',()=>assert.equal(validateRoster(parseCSV('Name\n=1+1'),{name:0})[0].name,'=1+1'));
test('size limit',()=>assert.throws(()=>parseCSV('x'.repeat(MAX_BYTES+1))));
test('row limit',()=>assert.throws(()=>parseCSV('Name\n'+'A\n'.repeat(10001))));
console.log(count+' tests passed');
